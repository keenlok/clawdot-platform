def fixture_repo(tmp_path):
    repo = tmp_path / "repo"
    repo.mkdir()
    env = {
        "PATH": os.environ["PATH"],
        "HOME": str(tmp_path),
        "GIT_CONFIG_NOSYSTEM": "1",
        "GIT_CONFIG_GLOBAL": os.devnull,
    }

    def git(*args):
        return subprocess.check_output(["git", "-C", str(repo), *args], env=env).decode().strip()

    git("init", "-q")
    git("config", "user.name", "Synthetic fixture")
    git("config", "user.email", "test@example.invalid")
    git("config", "core.hooksPath", os.devnull)
    (repo / "packages/demo/src/demo").mkdir(parents=True)
    (repo / "packages/demo/tests").mkdir()
    (repo / "packages/demo/src/demo/plugin.py").write_text("value = 'baseline'\n")
    (repo / "packages/demo/src/demo/unchanged.py").write_text("value = 42\n")
    (repo / "packages/demo/tests/test_plugin.py").write_text("# synthetic source, never executed\n")
    (repo / "uv.lock").write_text("synthetic locked dependency inventory\n")
    git("add", ".")
    git("commit", "-qm", "baseline fixture")
    return repo, git


def bundle(repo, commit):
    return build_baseline_bundle(
        repo,
        commit,
        policy_digest="a" * 64,
        allowed_paths=("packages/demo/src/demo/plugin.py",),
        source_roots=("packages/demo/src",),
        test_paths=("packages/demo/tests",),
        worker_source=b"# fixed worker\n",
        harness_source=b"# fixed harness\n",
    )


def install_snapshot(artifact, root):
    root.mkdir()
    # Test fixture writes only the regular entries generated by our builder.
    with tarfile.open(fileobj=io.BytesIO(artifact.source_tar)) as archive:
        for entry in archive:
            assert entry.isfile() and not entry.name.startswith("/")
            path = root / entry.name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(archive.extractfile(entry).read())
            path.chmod(entry.mode)


def test_actual_git_baseline_is_staged_before_allowed_overlay(tmp_path):
    repo, git = fixture_repo(tmp_path)
    commit = git("rev-parse", "HEAD")
    artifact = bundle(repo, commit)
    document = json.loads(artifact.manifest)
    assert document["version"] == 2
    assert document["baseline_commit"] == commit
    assert document["baseline_snapshot"]["tree"] == git("show", "-s", "--format=%T", commit)
    assert (
        document["baseline_snapshot"]["lock_digest"]
        == hashlib.sha256((repo / "uv.lock").read_bytes()).hexdigest()
    )
    snapshot = SnapshotManifest.from_value(document["baseline_snapshot"])
    installed = tmp_path / "installed"
    install_snapshot(artifact, installed)
    candidate = tmp_path / "candidate"
    prepare_baseline(snapshot, installed, candidate)
    overlay_files(
        candidate,
        {"packages/demo/src/demo/plugin.py": "value = 'candidate'\n"},
        tuple(document["allowed_paths"]),
    )
    assert (candidate / "packages/demo/src/demo/unchanged.py").read_text() == "value = 42\n"
    assert (candidate / "packages/demo/src/demo/plugin.py").read_text() == "value = 'candidate'\n"
    assert (installed / "packages/demo/src/demo/plugin.py").read_text() == "value = 'baseline'\n"
    assert pytest_arguments(snapshot) == (
        "--import-mode=importlib",
        "-q",
        "-p",
        "pytest_asyncio.plugin",
        "-m",
        "not integration and not browser and not sandbox_integration",
        "packages/demo/tests",
    )


def test_changed_installed_blob_or_symlink_is_rejected_without_executing_source(tmp_path):
    repo, git = fixture_repo(tmp_path)
