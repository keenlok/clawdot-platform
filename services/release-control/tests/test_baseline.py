def test_image_recipe_requires_immutable_parent_and_offline_installation(tmp_path):
    repo, git = fixture_repo(tmp_path)
    artifact = bundle(repo, git("rev-parse", "HEAD"))
    with pytest.raises(BaselineError):
        worker_image_recipe("python:latest", artifact.manifest, dependency_cache_digest="c" * 64)
    recipe = worker_image_recipe(
        "example.invalid/worker-base@sha256:" + "b" * 64,
        artifact.manifest,
        dependency_cache_digest="c" * 64,
    )
    assert "--offline" in recipe and "--frozen" in recipe and "--network=none" in recipe
    assert "COPY --chmod=0600 baseline.tar /opt/chatcore-release/baseline.tar" in recipe
    assert "--prepare-baseline " + artifact.manifest_digest in recipe
    assert "ADD baseline.tar" not in recipe
    assert "curl" not in recipe and "apt-get" not in recipe


def test_dependency_cache_hash_and_archive_paths_are_checked_before_install(tmp_path):
    from chatcore_release_control.monorepo_harness import prepare_dependency_cache

    content = io.BytesIO()
    with tarfile.open(fileobj=content, mode="w") as archive:
        info = tarfile.TarInfo("wheels/synthetic.whl")
        info.size = 4
        archive.addfile(info, io.BytesIO(b"data"))
    raw = content.getvalue()
    source = tmp_path / "cache.tar"
    source.write_bytes(raw)
    target = tmp_path / "cache"
    prepare_dependency_cache(source, hashlib.sha256(raw).hexdigest(), target)
    assert (target / "wheels/synthetic.whl").read_bytes() == b"data"
    with pytest.raises(HarnessError):
        prepare_dependency_cache(source, "f" * 64, tmp_path / "bad-hash")
    malicious = io.BytesIO()
    with tarfile.open(fileobj=malicious, mode="w") as archive:
        info = tarfile.TarInfo("../escape")
        info.size = 4
        archive.addfile(info, io.BytesIO(b"data"))
    source.write_bytes(malicious.getvalue())
    with pytest.raises(HarnessError):
        prepare_dependency_cache(
            source, hashlib.sha256(source.read_bytes()).hexdigest(), tmp_path / "bad-cache"
        )
    assert not (tmp_path / "escape").exists()


