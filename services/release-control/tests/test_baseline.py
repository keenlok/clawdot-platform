@pytest.mark.parametrize(
    "corruption", ["extra", "missing", "content", "mode", "symlink", "duplicate"]
)
def test_baseline_archive_rejects_changed_entries_even_with_matching_archive_hash(
    tmp_path, corruption
):
    repo, git = fixture_repo(tmp_path)
    artifact = bundle(repo, git("rev-parse", "HEAD"))
    snapshot = SnapshotManifest.from_value(json.loads(artifact.manifest)["baseline_snapshot"])
    altered = io.BytesIO()
    with tarfile.open(fileobj=io.BytesIO(artifact.source_tar)) as original:
        with tarfile.open(fileobj=altered, mode="w") as output:
            for index, member in enumerate(original):
                data = original.extractfile(member).read()
                if index == 0:
                    if corruption == "missing":
                        continue
                    if corruption == "content":
                        data = b"x" * len(data)
                    if corruption == "mode":
                        member.mode = 0o777
                    if corruption == "symlink":
                        member.type = tarfile.SYMTYPE
                        member.linkname = "/outside"
                output.addfile(member, io.BytesIO(data))
                if index == 0 and corruption == "duplicate":
                    output.addfile(member, io.BytesIO(data))
            if corruption == "extra":
                info = tarfile.TarInfo("secrets/synthetic.txt")
                info.size = 4
                output.addfile(info, io.BytesIO(b"data"))
    raw = altered.getvalue()
    source = tmp_path / "baseline.tar"
    source.write_bytes(raw)
    snapshot = replace(snapshot, archive_digest=hashlib.sha256(raw).hexdigest())
    target = tmp_path / "installed"
    with pytest.raises(HarnessError):
        install_baseline_archive(source, snapshot, target)
    assert not target.exists()


